#!/usr/bin/env python3
"""Generate components/winamp_display/voice_font.h: a compact VLW font
(ASCII + Cyrillic + Hebrew + punctuation) rendered from DejaVu Sans.

Usage: python3 tools/gen_voice_font.py [large_px] [small_px]
"""
import struct
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

TTF = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
OUT = Path(__file__).resolve().parent.parent / "components/winamp_display/voice_font.h"
SIZE = int(sys.argv[1]) if len(sys.argv) > 1 else 16
SMALL = int(sys.argv[2]) if len(sys.argv) > 2 else 12

RANGES = [
    (0x20, 0x7E),      # ASCII
    (0xB0, 0xB0),      # degree
    (0x401, 0x401),    # Ё
    (0x410, 0x44F),    # Cyrillic
    (0x451, 0x451),    # ё
    (0x5D0, 0x5EA),    # Hebrew letters
    (0x5F3, 0x5F4),    # geresh, gershayim
    (0x2013, 0x2014),  # dashes
    (0x2018, 0x201E),  # quotes
    (0x2026, 0x2026),  # ellipsis
    (0x20AA, 0x20AA),  # shekel
]

codes = [c for a, b in RANGES for c in range(a, b + 1)]


def build(size):
    font = ImageFont.truetype(TTF, size)
    ascent, descent = font.getmetrics()
    glyphs = []
    for cp in codes:
        ch = chr(cp)
        adv = int(round(font.getlength(ch)))
        if ch == " ":
            glyphs.append((cp, 0, 0, adv, 0, 0, b""))
            continue
        l, t, r, b = font.getbbox(ch, anchor="ls")
        w, h = r - l, b - t
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-l, -t), ch, font=font, anchor="ls", fill=255)
        glyphs.append((cp, h, w, adv, -t, l, img.tobytes()))
    blob = struct.pack(">6i", len(glyphs), 11, size, 0, ascent, descent)
    for cp, h, w, adv, dy, dx, _ in glyphs:
        blob += struct.pack(">7i", cp, h, w, adv, dy, dx, 0)
    for g in glyphs:
        blob += g[6]
    return blob


lines = [
    "// Generated by tools/gen_voice_font.py - do not edit.",
    f"// DejaVu Sans {SIZE}px and {SMALL}px, ASCII + Cyrillic + Hebrew, VLW format, in flash.",
    "#pragma once",
    "#include <stdint.h>",
    "",
    "namespace esphome {",
    "namespace winamp_display {",
    "",
]
total = 0
for name, size in (("VOICE_FONT_VLW", SIZE), ("VOICE_FONT_SMALL_VLW", SMALL)):
    blob = build(size)
    total += len(blob)
    lines.append(f"alignas(4) static const uint8_t {name}[] = {{")
    for i in range(0, len(blob), 24):
        lines.append("    " + ", ".join(f"0x{x:02X}" for x in blob[i:i + 24]) + ",")
    lines += ["};", ""]
lines += ["}  // namespace winamp_display", "}  // namespace esphome", ""]
OUT.write_text("\n".join(lines))
print(f"{OUT}: {total} bytes")
